/**
 * filterFiles：忽略规则（注入）、二进制、纯删除、生成文件标记。
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { filterFiles, GENERATED_MARKERS, isGeneratedFile } from '../../src/diff/filter.ts';
import { parseDiff } from '../../src/diff/parse.ts';
import type { DiffFile } from '../../src/diff/types.ts';
import { loadFixture } from './helpers.ts';

function fileOf(diffText: string): DiffFile {
  const files = parseDiff(diffText);
  assert.equal(files.length, 1);
  return files[0] as DiffFile;
}

test('忽略规则通过注入的 isIgnored 生效，保留顺序不变', () => {
  const files = parseDiff(loadFixture('combined'));
  const { kept, ignored } = filterFiles(files, (p) => p.startsWith('pkg/'));
  assert.deepEqual(kept.map((f) => f.path), ['blank.txt']);
  assert.deepEqual(ignored, [
    { path: 'pkg/one.ts', reason: '命中忽略规则' },
    { path: 'pkg/three.ts', reason: '命中忽略规则' },
    { path: 'pkg/two.ts', reason: '命中忽略规则' },
  ]);
});

test('二进制文件被过滤并注明原因', () => {
  const files = parseDiff(loadFixture('binary'));
  const { kept, ignored } = filterFiles(files, () => false);
  assert.deepEqual(kept, []);
  assert.deepEqual(ignored, [{ path: 'logo.bin', reason: '二进制文件' }]);
});

test('纯删除文件被过滤（行内评论挂不上新侧行）', () => {
  const files = parseDiff(loadFixture('deleted'));
  const { kept, ignored } = filterFiles(files, () => false);
  assert.deepEqual(kept, []);
  assert.deepEqual(ignored, [{ path: 'doomed.txt', reason: '纯删除文件' }]);
});

test('忽略规则优先于内置规则（同一文件命中多条时取第一条原因）', () => {
  const files = parseDiff(loadFixture('binary'));
  const { ignored } = filterFiles(files, () => true);
  assert.deepEqual(ignored, [{ path: 'logo.bin', reason: '命中忽略规则' }]);
});

test('首 5 行含 @generated 即视为生成文件', () => {
  const body = (first: string) =>
    [
      'diff --git a/gen.ts b/gen.ts',
      '--- a/gen.ts',
      '+++ b/gen.ts',
      '@@ -1,5 +1,5 @@',
      `+${first}`,
      ' line2',
      ' line3',
      ' line4',
      ' line5',
      '',
    ].join('\n');
  assert.equal(isGeneratedFile(fileOf(body('// @generated by protoc'))), true);
  const { ignored } = filterFiles([fileOf(body('// @generated by protoc'))], () => false);
  assert.deepEqual(ignored, [{ path: 'gen.ts', reason: '生成文件标记' }]);
});

test('首 5 行含 DO NOT EDIT 即视为生成文件', () => {
  const text = [
    'diff --git a/gen.go b/gen.go',
    '--- a/gen.go',
    '+++ b/gen.go',
    '@@ -1,3 +1,3 @@',
    '+// Code generated by thing. DO NOT EDIT.',
    ' package main',
    '',
  ].join('\n');
  const { kept, ignored } = filterFiles([fileOf(text)], () => false);
  assert.deepEqual(kept, []);
  assert.deepEqual(ignored, [{ path: 'gen.go', reason: '生成文件标记' }]);
});

test('标记出现在第 6 行及以后不判定为生成文件（只采样前 5 行）', () => {
  const text = [
    'diff --git a/hand.ts b/hand.ts',
    '--- a/hand.ts',
    '+++ b/hand.ts',
    '@@ -1,7 +1,7 @@',
    '+ line1',
    ' line2',
    ' line3',
    ' line4',
    ' line5',
    '+// @generated',
    ' line7',
    '',
  ].join('\n');
  assert.equal(isGeneratedFile(fileOf(text)), false);
  const { kept, ignored } = filterFiles([fileOf(text)], () => false);
  assert.equal(kept.length, 1);
  assert.deepEqual(ignored, []);
});

test('生成标记大小写敏感（@generated / DO NOT EDIT 的惯用大小写）', () => {
  assert.deepEqual(GENERATED_MARKERS, ['@generated', 'DO NOT EDIT']);
  const text = (marker: string) =>
    [
      'diff --git a/x.ts b/x.ts',
      '--- a/x.ts',
      '+++ b/x.ts',
      '@@ -1,2 +1,2 @@',
      `+// ${marker}`,
      ' line2',
      '',
    ].join('\n');
  assert.equal(isGeneratedFile(fileOf(text('@Generated'))), false, '大小写不同不算');
  assert.equal(isGeneratedFile(fileOf(text('do not edit'))), false, '大小写不同不算');
});

test('删除行不参与生成标记采样（看重的是新文件内容）', () => {
  const text = [
    'diff --git a/keep.ts b/keep.ts',
    '--- a/keep.ts',
    '+++ b/keep.ts',
    '@@ -1,3 +1,3 @@',
    '-// @generated old header',
    '+// normal header',
    ' line2',
    '',
  ].join('\n');
  assert.equal(isGeneratedFile(fileOf(text)), false);
});

test('正常夹具全部保留', () => {
  for (const name of ['added', 'modified', 'renamed-modified', 'spaces', 'multi-hunk', 'quoted-path']) {
    const { kept, ignored } = filterFiles(parseDiff(loadFixture(name)), () => false);
    assert.equal(kept.length, parseDiff(loadFixture(name)).length, name);
    assert.deepEqual(ignored, [], name);
  }
});
